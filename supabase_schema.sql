-- 4. Enable Row-Level Security (RLS) & Triggers
alter table public.allowed_users enable row level security;
alter table public.lookup_values enable row level security;

-- Whitelist table policies
drop policy if exists "Users can view own whitelist entry or admins view all" on public.allowed_users;
create policy "Users can view own whitelist entry or admins view all"
  on public.allowed_users
  for select
  using (lower(email) = public.current_user_email() or public.is_admin());

drop policy if exists "Admins can manage allowed_users" on public.allowed_users;
create policy "Admins can manage allowed_users"
  on public.allowed_users
  for all
  using (public.is_admin())
  with check (public.is_admin());

-- Lookup table policies
drop policy if exists "Allowed users can read lookups" on public.lookup_values;
create policy "Allowed users can read lookups"
  on public.lookup_values
  for select
  using (public.is_allowed_user());

drop policy if exists "Admins can manage lookups" on public.lookup_values;
create policy "Admins can manage lookups"
  on public.lookup_values
  for all
  using (public.is_admin())
  with check (public.is_admin());

-- Apply uniform RLS policies and updated_at triggers across all 7 operational tables
do $$
declare
  tbl text;
  tables text[] := array[
    'incoming_outgoing_docs',
    'email_logs',
    'memo_ao_external',
    'personnel_appointments',
    'cfnr_memos',
    'cfnr_admin_orders',
    'ppmp_procurement'
  ];
begin
  foreach tbl in array tables loop
    execute format('alter table public.%I enable row level security;', tbl);

    execute format('drop policy if exists "Allowed users can read %I" on public.%I;', tbl, tbl);
    execute format(
      'create policy "Allowed users can read %I" on public.%I for select using (public.is_allowed_user());',
      tbl, tbl
    );

    execute format('drop policy if exists "Staff can insert %I" on public.%I;', tbl, tbl);
    execute format(
      'create policy "Staff can insert %I" on public.%I for insert with check (public.can_write());',
      tbl, tbl
    );

    execute format('drop policy if exists "Staff can update %I" on public.%I;', tbl, tbl);
    execute format(
      'create policy "Staff can update %I" on public.%I for update using (public.can_write()) with check (public.can_write());',
      tbl, tbl
    );

    execute format('drop policy if exists "Staff can delete %I" on public.%I;', tbl, tbl);
    execute format(
      'create policy "Staff can delete %I" on public.%I for delete using (public.can_write());',
      tbl, tbl
    );

    execute format('drop trigger if exists trg_%I_updated_at on public.%I;', tbl, tbl);
    execute format(
      'create trigger trg_%I_updated_at before update on public.%I for each row execute function public.set_updated_at();',
      tbl, tbl
    );
  end loop;
end;
$$;

