-- 1. Authorized Users Whitelist
create table if not exists public.allowed_users (
  id uuid primary key default gen_random_uuid(),
  email text not null,
  full_name text,
  role text not null default 'staff' check (role in ('admin', 'staff', 'viewer')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index if not exists idx_allowed_users_email_lower
  on public.allowed_users (lower(email));

-- 2. Security Helper Functions (used by RLS policies)
create or replace function public.current_user_email()
returns text
language sql
stable
as $$
  select lower(coalesce(auth.jwt() ->> 'email', ''));
$$;

create or replace function public.is_allowed_user()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1
    from public.allowed_users
    where lower(email) = public.current_user_email()
      and is_active = true
  );
$$;

create or replace function public.can_write()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1
    from public.allowed_users
    where lower(email) = public.current_user_email()
      and role in ('admin', 'staff')
      and is_active = true
  );
$$;

create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1
    from public.allowed_users
    where lower(email) = public.current_user_email()
      and role = 'admin'
      and is_active = true
  );
$$;

-- Auto-update updated_at timestamp trigger
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

